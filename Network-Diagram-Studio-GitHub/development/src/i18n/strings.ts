/**
 * English source text is the lookup key — see the comment in `useT.ts` for why.
 *
 * Deliberately NOT in here, and deliberately never translated:
 *   - Azure resource and product names (Microsoft ships those untranslated)
 *   - anything the user typed: node names, subtitles, notes, custom fields
 *   - template names/descriptions and icon labels
 * Translating those would either fight Microsoft's own terminology or corrupt
 * the user's own content, so the canvas stays in whatever language they wrote.
 *
 * The per-resource "Details" prose lives in `strings-knowledge.ts` so this
 * file stays navigable; `DICT` merges the two per language at the bottom.
 *
 * A missing entry is not a bug — `translate()` falls back to the English
 * source, so a partial dictionary degrades to a readable mixed UI rather than
 * to blank space or `header.export.button`-style debug tokens.
 */
